/* Рисует карточки отзывов. base — путь до папки прототипа ('' на страницах прототипа). */
function renderReviews(el, base) {
  const nbsp = t => String(t).replace(/(^|[\s(«])(в|во|и|с|со|из|к|ко|на|по|за|от|до|для|о|об|у|не|а|но|или|без)\s+/gi, '$1$2 ');
  const byId = id => (typeof PRODUCTS !== 'undefined' ? PRODUCTS.find(p => p.id === id) : null);
  el.innerHTML = REVIEWS.map(r => {
    const p = byId(r.id);
    return `<article class="rv">
      <div class="rv-top"><span class="rv-stars" aria-label="Оценка 5 из 5">★★★★★</span><span class="rv-src">Wildberries</span></div>
      <p class="rv-text">«${nbsp(r.text)}»</p>
      <div class="rv-foot">
        <b>${r.name}</b><span>${r.date}</span>
        ${p ? `<a class="rv-prod" href="${base}product.html?id=${p.id}">${nbsp(p.name)}</a>` : ''}
        <a class="rv-link" href="https://www.wildberries.ru/catalog/${r.wb}/feedbacks" target="_blank" rel="noopener">Смотреть на&nbsp;Wildberries</a>
      </div>
    </article>`;
  }).join('');
}
